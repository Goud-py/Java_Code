package Chapter02;

public class java01_Variable {
    public static void main(String[] args) {
        // TODO 变量
        // 所谓的变量，其实就是可以改变的向量存储
        //1. 变量的声明
        String name;
        //2. 变量的赋值
        name= "张三";
        //3. 变量的使用
        System.out.println(name);
        //将变量的声明和赋值在一行代码中完成
        String username="李四";
        System.out.println(username);
    }
}
